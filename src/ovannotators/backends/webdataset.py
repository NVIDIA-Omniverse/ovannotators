"""Package explicitly grouped samples into portable WebDataset tar shards."""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import tarfile
import tempfile
from dataclasses import dataclass, field, replace
from decimal import Decimal
from pathlib import Path
from importlib import metadata as _metadata
from typing import Any, Iterable, Literal, Mapping
from uuid import uuid4

from ovannotators.backends._base import Backend
from ovannotators.exceptions import ConfigurationError, PackagingError

# USTAR stores member sizes in 11 octal digits.
_MAX_MEMBER_BYTES = 8**11 - 1
_SUFFIX = re.compile(r"[a-z0-9](?:[a-z0-9_.-]{0,38}[a-z0-9_-])?")


def _size_bytes(value: int | str) -> int:
    if isinstance(value, bool):
        raise ConfigurationError(
            "Archive size must be a positive integer or explicit size string"
        )
    if isinstance(value, int):
        result = value
    elif isinstance(value, str):
        match = re.fullmatch(
            r"\s*(\d+(?:\.\d+)?)\s*(B|KB|MB|GB|TB|KiB|MiB|GiB|TiB)\s*", value
        )
        if not match:
            raise ConfigurationError(
                "Use bytes or an explicit unit, such as '512 MiB' or '1 GB'"
            )
        units = {
            "B": 1,
            "KB": 1000,
            "MB": 1000**2,
            "GB": 1000**3,
            "TB": 1000**4,
            "KiB": 1024,
            "MiB": 1024**2,
            "GiB": 1024**3,
            "TiB": 1024**4,
        }
        exact = Decimal(match[1]) * units[match[2]]
        if exact != int(exact):
            raise ConfigurationError("Archive size must resolve to whole bytes")
        result = int(exact)
    else:
        raise ConfigurationError("Archive size must be an integer or size string")
    if result < tarfile.RECORDSIZE:
        raise ConfigurationError(
            "Archive size must be at least 10240 bytes (one tar record)"
        )
    return result


def _identifier(value: str | int) -> str:
    if isinstance(value, bool) or not isinstance(value, (str, int)):
        raise PackagingError(
            "Identifiers must be lowercase portable strings or integers"
        )
    text = str(value)
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]{0,39}", text):
        raise PackagingError(
            "Identifiers must be 1-40 lowercase letters, digits, underscores or hyphens"
        )
    if text in {"con", "prn", "aux", "nul"} or re.fullmatch(r"(?:com|lpt)[1-9]", text):
        raise PackagingError("Identifiers cannot be reserved Windows device names")
    return text


def _component_suffix(suffix: object) -> str:
    """Return a portable, non-reserved component suffix or raise."""
    if (
        not isinstance(suffix, str)
        or not _SUFFIX.fullmatch(suffix)
        or suffix == "metadata.json"
    ):
        raise PackagingError(f"Invalid or reserved component suffix: {suffix!r}")
    return suffix


def _package_version() -> str:
    try:
        return _metadata.version("ovannotators")
    except _metadata.PackageNotFoundError:
        return "0.0.0+unknown"


def _archive_size(payload: int) -> int:
    """Include tar closing blocks and record padding in a member footprint."""
    return (
        (payload + 1024 + tarfile.RECORDSIZE - 1) // tarfile.RECORDSIZE
    ) * tarfile.RECORDSIZE


@dataclass
class WebDatasetPackagerConfig:
    """Configure shard limits and dataset identity.

    Attributes:
        max_shard_bytes: Final uncompressed tar limit; integer bytes or explicit
            decimal/binary units. Normalized to integer bytes at construction.
        max_samples_per_shard: Optional positive sample limit.
        max_episodes_per_shard: Optional positive distinct-episode limit.
        allow_episode_spanning: Allow rotation between samples of an episode.
        oversized_episode_policy: ``error`` or ``dedicated_shard``. With spanning
            enabled, the same policy applies to an oversized individual sample.
        dataset_id: Portable namespace, generated by default. Existing namespaces
            are rejected; resuming and overwriting are not supported.
    """

    max_shard_bytes: int | str = "512 MiB"
    max_samples_per_shard: int | None = None
    max_episodes_per_shard: int | None = None
    allow_episode_spanning: bool = False
    oversized_episode_policy: Literal["error", "dedicated_shard"] = "error"
    dataset_id: str = field(default_factory=lambda: uuid4().hex)

    def __post_init__(self) -> None:
        self.max_shard_bytes = _size_bytes(self.max_shard_bytes)
        self.dataset_id = _identifier(self.dataset_id)
        for value in (self.max_samples_per_shard, self.max_episodes_per_shard):
            if value is not None and (
                isinstance(value, bool) or not isinstance(value, int) or value < 1
            ):
                raise ConfigurationError(
                    "Shard count limits must be positive integers or None"
                )
        if not isinstance(self.allow_episode_spanning, bool):
            raise ConfigurationError("allow_episode_spanning must be a boolean")
        if self.oversized_episode_policy not in {"error", "dedicated_shard"}:
            raise ConfigurationError(
                "oversized_episode_policy must be 'error' or 'dedicated_shard'"
            )


@dataclass
class SampleFiles:
    """Describe one complete sample using already encoded local files.

    Attributes:
        key: Episode-local unique portable identifier.
        files: Component suffix to local file, such as ``jpg`` or ``depth.npy``.
            Encoded bytes are preserved. ``metadata.json`` is reserved.
        metadata: JSON-serializable application metadata, stored inside the
            generated ``metadata.json`` component.
    """

    key: str | int
    files: Mapping[str, str | Path]
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass
class _Sample:
    key: str
    episode: str
    files: list[tuple[str, Path]]
    size: int


class WebDatasetPackager:
    """Package explicitly grouped samples into shards on an ordinary backend.

    The packager wraps a storage backend; it is not a ``Backend`` and is not a
    writer destination. It accepts complete episodes through ``pack_episode``.
    Use ``DatasetCapture`` for writers. Ordinary storage backends need no new
    finalization calls. Temporary disk holds episodes and pending shards;
    publication materializes one complete shard in memory because the storage
    protocol accepts bytes, so a dedicated oversized shard needs memory for its
    whole size. Instances are single-use and single-threaded.

    An episode rejected by validation or shard limits is discarded and the
    packager stays open, so the caller may retry or skip it. A storage failure
    aborts the packager. After an abort, published shards remain without a
    completion manifest; delete the ``dataset_id`` prefix to reuse it.
    """

    def __init__(
        self, storage: Backend, config: WebDatasetPackagerConfig | None = None
    ) -> None:
        """Initialize packaging and reject an existing dataset namespace.

        Args:
            storage: Disk, object-store or HTTP destination.
            config: Shard limits and identity.
        """
        self.storage = storage
        self.config = (
            replace(config) if config is not None else WebDatasetPackagerConfig()
        )
        self._prefix = self.config.dataset_id + "/"
        if storage.list(self._prefix):
            raise PackagingError(
                f"Dataset namespace already exists: {self.config.dataset_id}"
            )
        self._tmp = tempfile.TemporaryDirectory(prefix="ovannotators-wds-")
        self._root = Path(self._tmp.name)
        self._episodes: set[str] = set()
        self._pending: list[_Sample] = []
        self._pending_episodes: set[str] = set()
        self._payload = 0
        self._shards: list[dict[str, Any]] = []
        self._state = "open"

    def __enter__(self) -> WebDatasetPackager:
        self._ensure_open()
        return self

    def __exit__(self, exc_type: object, exc: object, tb: object) -> None:
        if exc_type is not None:
            self.abort()
        else:
            try:
                self.finalize()
            except BaseException:
                self.abort()
                raise

    def _ensure_open(self) -> None:
        if self._state != "open":
            raise PackagingError(f"WebDataset packager is {self._state}")

    @property
    def is_open(self) -> bool:
        """Whether the packager still accepts episodes."""
        return self._state == "open"

    def _fits(self, samples: list[_Sample], *, append: bool = False) -> bool:
        cfg = self.config
        payload = sum(s.size for s in samples) + (self._payload if append else 0)
        count = len(samples) + (len(self._pending) if append else 0)
        episodes = {s.episode for s in samples}
        if append and cfg.max_episodes_per_shard is not None:
            episodes |= self._pending_episodes
        return (
            _archive_size(payload) <= cfg.max_shard_bytes
            and (
                cfg.max_samples_per_shard is None or count <= cfg.max_samples_per_shard
            )
            and (
                cfg.max_episodes_per_shard is None
                or len(episodes) <= cfg.max_episodes_per_shard
            )
        )

    def _stage(
        self, episode: str, samples: Iterable[SampleFiles], root: Path
    ) -> list[_Sample]:
        result = []
        seen = set()
        for sample in samples:
            key = _identifier(sample.key)
            if key in seen:
                raise PackagingError(
                    f"Duplicate sample key in episode {episode}: {key}"
                )
            seen.add(key)
            if not sample.files:
                raise PackagingError("A sample must contain at least one encoded file")
            sample_dir = root / key
            sample_dir.mkdir(parents=True)
            members = []
            for suffix, source in sorted(sample.files.items()):
                _component_suffix(suffix)
                if Path(source).stat().st_size > _MAX_MEMBER_BYTES:
                    raise PackagingError(
                        f"Component {suffix} of sample {key} exceeds the "
                        "8 GiB USTAR member limit"
                    )
                target = sample_dir / suffix
                shutil.copyfile(source, target)
                members.append((suffix, target))
            meta = sample_dir / "metadata.json"
            meta.write_text(
                json.dumps(
                    {
                        "schema_version": 1,
                        "dataset_id": self.config.dataset_id,
                        "episode_id": episode,
                        "sample_id": key,
                        "metadata": dict(sample.metadata),
                    },
                    allow_nan=False,
                ),
                encoding="utf-8",
            )
            members.append(("metadata.json", meta))
            sample_key = f"{self.config.dataset_id}/episode-{episode}/sample-{key}"
            files = [(f"{sample_key}.{suffix}", path) for suffix, path in members]
            size = 0
            for name, path in files:
                info = tarfile.TarInfo(name)
                info.size = path.stat().st_size
                size += (
                    len(info.tobuf(format=tarfile.USTAR_FORMAT))
                    + ((info.size + 511) // 512) * 512
                )
            result.append(_Sample(sample_key, episode, files, size))
        if not result:
            raise PackagingError(f"Episode {episode} contains no samples")
        return result

    def pack_episode(
        self, episode_id: str | int, samples: Iterable[SampleFiles]
    ) -> None:
        """Stage an episode and append complete units according to shard limits.

        Args:
            episode_id: Dataset-wide unique portable episode identifier.
            samples: Complete samples with unique episode-local keys.

        Raises:
            PackagingError: On duplicate identity, an empty episode, invalid
                component names or oversized units. The episode is discarded
                and the packager stays open. Dedicated shards may exceed
                byte/sample limits, but never split samples.
        """
        self._ensure_open()
        episode = _identifier(episode_id)
        if episode in self._episodes:
            raise PackagingError(f"Duplicate episode: {episode}")
        root = self._root / f"episode-{episode}"
        root.mkdir()
        try:
            staged = self._stage(episode, samples, root)
            units = (
                [[s] for s in staged]
                if self.config.allow_episode_spanning
                else [staged]
            )
            if self.config.oversized_episode_policy == "error" and any(
                not self._fits(unit) for unit in units if unit
            ):
                raise PackagingError(
                    f"Episode {episode} exceeds shard limits; enable spanning or dedicated_shard"
                )
        except BaseException:
            shutil.rmtree(root)
            raise
        self._episodes.add(episode)
        try:
            for unit in units:
                if not unit:
                    continue
                if self._pending and not self._fits(unit, append=True):
                    self._publish()
                self._pending.extend(unit)
                self._pending_episodes.add(episode)
                self._payload += sum(s.size for s in unit)
                if not self._fits(unit):
                    self._publish()
        except BaseException:
            self.abort()
            raise

    def _publish(self) -> None:
        if not self._pending:
            return
        path = f"{self._prefix}shard-{len(self._shards):06d}.tar"
        local = self._root / "pending.tar"
        with tarfile.open(local, "w", format=tarfile.USTAR_FORMAT) as archive:
            for sample in self._pending:
                for name, source in sample.files:
                    info = tarfile.TarInfo(name)
                    info.size = source.stat().st_size
                    info.mode = 0o644
                    info.mtime = 0
                    with source.open("rb") as stream:
                        archive.addfile(info, stream)
        payload = local.read_bytes()
        if len(payload) != _archive_size(self._payload):
            raise PackagingError("Archive accounting does not match encoded tar size")
        if self.storage.exists(path):
            raise PackagingError(f"Refusing to overwrite shard: {path}")
        self.storage.write(path, payload)
        self._shards.append(
            {
                "path": path,
                "bytes": len(payload),
                "sha256": hashlib.sha256(payload).hexdigest(),
                "samples": len(self._pending),
                "episodes": sorted({s.episode for s in self._pending}),
                "episode_samples": {
                    episode: sum(s.episode == episode for s in self._pending)
                    for episode in sorted({s.episode for s in self._pending})
                },
                "oversized": not self._fits(self._pending),
            }
        )
        for sample in self._pending:
            for _, source in sample.files:
                source.unlink()
            sample.files[0][1].parent.rmdir()
        local.unlink()
        self._pending.clear()
        self._pending_episodes.clear()
        self._payload = 0

    def finalize(
        self,
        metadata: Mapping[str, Any] | None = None,
        *,
        auxiliary: Mapping[str, bytes] | None = None,
    ) -> None:
        """Publish the final shard and completion manifest, idempotently.

        Args:
            metadata: Dataset schema/format information recorded in the manifest.
            auxiliary: Named metadata files published before the completion
                manifest, with their paths and checksums recorded in it.

        Raises:
            PackagingError: If ``metadata`` is not finite JSON or an auxiliary
                name or payload is invalid. The packager stays open so the call
                can be repeated with valid input.
        """
        if self._state == "complete":
            return
        self._ensure_open()
        try:
            metadata_json = json.loads(
                json.dumps(dict(metadata or {}), allow_nan=False)
            )
        except (TypeError, ValueError) as exc:
            raise PackagingError(
                f"Manifest metadata must be finite JSON: {exc}"
            ) from exc
        auxiliary_items = sorted((auxiliary or {}).items())
        for name, payload in auxiliary_items:
            if (
                not isinstance(name, str)
                or not re.fullmatch(r"[a-z0-9][a-z0-9_.-]{0,79}", name)
                or name.endswith(".")
            ):
                raise PackagingError(f"Invalid auxiliary metadata name: {name!r}")
            if not isinstance(payload, bytes):
                raise PackagingError(f"Auxiliary metadata {name} must be bytes")
        try:
            self._publish()
            auxiliary_records = []
            for name, payload in auxiliary_items:
                auxiliary_path = f"{self._prefix}auxiliary/{name}"
                if self.storage.exists(auxiliary_path):
                    raise PackagingError(f"Refusing to overwrite: {auxiliary_path}")
                self.storage.write(auxiliary_path, payload)
                auxiliary_records.append(
                    {
                        "path": auxiliary_path,
                        "bytes": len(payload),
                        "sha256": hashlib.sha256(payload).hexdigest(),
                    }
                )
            manifest = {
                "schema_version": 1,
                "format": "webdataset",
                "generator": {"name": "ovannotators", "version": _package_version()},
                "dataset_id": self.config.dataset_id,
                "max_shard_bytes": self.config.max_shard_bytes,
                "max_samples_per_shard": self.config.max_samples_per_shard,
                "max_episodes_per_shard": self.config.max_episodes_per_shard,
                "allow_episode_spanning": self.config.allow_episode_spanning,
                "oversized_episode_policy": self.config.oversized_episode_policy,
                "episodes": sorted(self._episodes),
                "shards": self._shards,
                "samples": sum(s["samples"] for s in self._shards),
                "metadata": metadata_json,
            }
            if auxiliary_records:
                manifest["auxiliary"] = auxiliary_records
            path = self._prefix + "manifest.json"
            if self.storage.exists(path):
                raise PackagingError(f"Refusing to overwrite manifest: {path}")
            self.storage.write(
                path, json.dumps(manifest, indent=2, allow_nan=False).encode()
            )
            self._state = "complete"
        except BaseException:
            self.abort()
            raise
        finally:
            self._tmp.cleanup()

    def abort(self) -> None:
        """Discard pending output without publishing a completion manifest.

        Shards already sent to storage remain available for diagnosis; they are
        not advertised as a completed dataset. Aborting is idempotent.
        """
        if self._state == "open":
            self._state = "aborted"
            self._pending.clear()
            self._pending_episodes.clear()
            self._tmp.cleanup()
