"""Produce a small Markdown failure report from a JUnit JSON sidecar."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any


def load_sidecar(path: Path) -> dict[str, Any]:
    """Load a JSON sidecar produced by ``generate_sidecar.py``."""
    return json.loads(path.read_text(encoding="utf-8"))


def load_changed_files(path: Path | None) -> list[str]:
    """Load changed files from a newline-delimited file."""
    if path is None or not path.exists():
        return []
    return [
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def categorize_failure(
    failure: dict[str, Any], changed_files: list[str]
) -> tuple[str, str]:
    """Categorize a failure using lightweight traceback and diff heuristics."""
    test_name = failure.get("test", "unknown")
    text = " ".join(str(failure.get(k, "")) for k in ("message", "text"))
    implicated = set(failure.get("implicated_files", []))
    changed = set(changed_files)

    infra_patterns = [
        (r"timeout|timed out", "Test timed out; this may be CI resource contention."),
        (
            r"MemoryError|OOM|out of memory",
            "Out-of-memory condition in the test environment.",
        ),
        (
            r"ConnectionError|ConnectionRefused|HTTPError|Temporary failure",
            "Network or external-service failure.",
        ),
        (
            r"PermissionError|EPERM|access is denied",
            "Permission or filesystem issue in the test environment.",
        ),
        (
            r"DLL load failed|cannot open shared object|No module named",
            "Runtime dependency or environment setup issue.",
        ),
    ]
    for pattern, reason in infra_patterns:
        if re.search(pattern, text, re.IGNORECASE):
            return "INFRASTRUCTURE", reason

    if implicated and changed and implicated & changed:
        files = ", ".join(f"`{f}`" for f in sorted(implicated & changed)[:3])
        return "PR_CODE", f"Traceback mentions changed file(s): {files}."

    if changed and any(Path(f).stem in test_name for f in changed):
        return "PR_CODE", "Test name appears related to a changed file."

    upstream_patterns = [
        (r"ovrtx|CUDA|cuda|PyNvVideoCodec|nvidia", "GPU/renderer dependency issue."),
        (r"boto3|S3|HTTP|httpx", "External storage/network dependency issue."),
    ]
    for pattern, reason in upstream_patterns:
        if re.search(pattern, text, re.IGNORECASE):
            return "UPSTREAM", reason

    if changed:
        return "UNKNOWN", "No direct correlation to changed files found."
    return "UNKNOWN", "No changed-file context available."


def generate_report(
    sidecar: dict[str, Any], changed_files: list[str], mode: str
) -> str:
    """Generate Markdown report for PR or nightly triage."""
    summary = sidecar.get("summary", {})
    failures = sidecar.get("failures", [])
    skips = sidecar.get("skips", [])
    title = "Nightly Test Triage" if mode == "nightly" else "Test Failure Analysis"

    lines = [f"## {title}", ""]
    lines.append(
        "Results: "
        f"{summary.get('passed', 0)} passed, "
        f"{summary.get('failed', len(failures))} failed, "
        f"{summary.get('skipped', len(skips))} skipped "
        f"out of {summary.get('total', '?')} tests."
    )
    lines.append("")

    if not failures:
        lines.append("✅ No failures detected.")
        lines.append("")
        lines.append("---")
        lines.append("Generated by `scripts/failure_analysis.py`.")
        return "\n".join(lines) + "\n"

    grouped: dict[str, list[tuple[dict[str, Any], str]]] = {}
    for failure in failures:
        category, reason = categorize_failure(failure, changed_files)
        grouped.setdefault(category, []).append((failure, reason))

    labels = [
        ("PR_CODE", "🎯 Possibly caused by this PR"),
        ("INFRASTRUCTURE", "🏗️ Infrastructure / environment"),
        ("UPSTREAM", "⬆️ Upstream or optional dependency"),
        ("UNKNOWN", "❓ Needs investigation"),
    ]
    for category, label in labels:
        items = grouped.get(category, [])
        if not items:
            continue
        lines.append(f"### {label} ({len(items)})")
        lines.append("")
        for failure, reason in items:
            lines.append(f"- `{failure.get('test', 'unknown')}` — {reason}")
            message = str(failure.get("message", "")).strip()
            if message:
                lines.append(f"  - `{message[:240]}`")
        lines.append("")

    lines.append("---")
    lines.append("Generated by `scripts/failure_analysis.py`.")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sidecar_json", type=Path, help="Path to JSON sidecar")
    parser.add_argument("--diff", type=Path, help="Changed-file list")
    parser.add_argument(
        "--output", "-o", type=Path, default=Path("failure-analysis.md")
    )
    parser.add_argument("--mode", choices=["pr", "nightly"], default="pr")
    args = parser.parse_args()

    sidecar = load_sidecar(args.sidecar_json)
    changed_files = load_changed_files(args.diff)
    report = generate_report(sidecar, changed_files, args.mode)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"Failure analysis written to {args.output}")


if __name__ == "__main__":
    main()
